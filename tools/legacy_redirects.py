#!/usr/bin/env python3
"""Redirect URLs the old site published that this one never built.

Before the ssg port (2026-08-23) the site was generated by the wiserone
CLI, which named date pages `/YYYY_MM_DD.html`. Those URLs are still in
Google's index and the Wayback Machine, and Search Console reports them
as 404s (for example /2026_05_31.html and /2026_08_16.html). The port
kept every date alive, but only under the new `/YYYY-MM-DD/` form.

Google also probes `/q` and `/q/`, the parent of every canonical quote
page, and ssg emits no index there.

Each gets a redirect page in the same shape `retire_redirects.py`
writes: a zero-delay meta refresh (the closest a static host gets to a
301), a rel=canonical at the destination, and a visible link. A date
goes straight to the canonical page of the quote it now shows, so the
redirect does not chain through a dated page that itself points
elsewhere; `/q/` goes to the archive, which lists every quote.

These pages are named `*.html` at the root and `q/index.html`, so they
never declare themselves canonical and the sitemap leaves them out.
"""

from __future__ import annotations

import datetime as dt
import html
import pathlib
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
from build_posts import (  # noqa: E402
    BASE, LEGACY, SITE, assign_slugs, daterange, for_date, load_pool)

PAGE = """<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>Moved — {title}</title>
<meta http-equiv="refresh" content="0; url={target}">
<link rel="canonical" href="{target}">
<style>
:root {{ color-scheme: light dark; }}
body {{ font: 1rem/1.6 system-ui, sans-serif; margin: 0; padding: 3rem 1.5rem;
        max-width: 34rem; background: #111; color: #f2f2f2; }}
a {{ color: #9cc3ff; }}
</style>
</head>
<body>
<h1>This page has moved</h1>
<p>You are being sent to <a href="{target}">{label}</a>.</p>
</body>
</html>
"""


def page(target: str, label: str) -> str:
    return PAGE.format(title=html.escape(SITE["title"]), target=target,
                       label=html.escape(label))


def legacy_dates() -> list[dt.date]:
    first = dt.date.fromisoformat(LEGACY["first"])
    last = dt.date.fromisoformat(LEGACY["last"])
    return list(daterange(first, last))


def main() -> int:
    out = pathlib.Path(sys.argv[1] if len(sys.argv) > 1 else "public")
    pool = load_pool()
    assign_slugs(pool)

    written = 0
    for d in legacy_dates():
        name = out / f"{d.strftime('%Y_%m_%d')}.html"
        # A real page at that address would win; none exists today.
        if name.exists():
            continue
        q = for_date(pool, d)
        name.write_text(page(f"{BASE}/q/{q['slug']}/",
                             d.strftime("%-d %B %Y")), encoding="utf-8")
        written += 1

    q_index = out / "q" / "index.html"
    if not q_index.exists():
        q_index.parent.mkdir(parents=True, exist_ok=True)
        q_index.write_text(page(f"{BASE}/archive/", "the archive"),
                           encoding="utf-8")

    print(f"legacy redirects: {written} dated /YYYY_MM_DD.html, /q/ → /archive/")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
